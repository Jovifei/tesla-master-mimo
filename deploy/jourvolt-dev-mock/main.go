type app struct {
	store              *store
	mock               provider
	provider           provider
	oauth              *teslaOAuth
	mockEnabled        bool
	mockHistoryEnabled bool
	mode               string
}

func (a *app) ServeHTTP(w http.ResponseWriter, r *http.Request) {
	if r.URL.Path == "/healthz" {
		a.json(w, http.StatusOK, map[string]any{
			"status": "ok", "mode": a.mode, "persistence": "postgres",
			"mock_history": a.mockHistoryEnabled,
		})
		return
	}
	if r.URL.Path == "/readyz" {
		a.readyz(w, r)
		return
	}
	if r.Method == http.MethodPost && r.URL.Path == "/v1/dev/mock-login" {
		if !a.mockEnabled {
			a.json(w, http.StatusNotFound, map[string]string{"error": "not_found"})
			return
		}
		a.mockLogin(w, r)
		return
	}
	if a.authRoute(w, r) {
		return
	}
	if r.Method == http.MethodPost && r.URL.Path == "/v1/session/refresh" {
		a.refresh(w, r)
		return
	}
	if r.Method == http.MethodPost && r.URL.Path == "/v1/session/logout" {
		a.logout(w, r)
		return
	}
	if r.Method == http.MethodDelete && r.URL.Path == "/v1/account" {
		a.deleteAccount(w, r)
		return
	}
	userID, ok := a.auth(w, r)
	if !ok {
		return
	}
	if r.URL.Path == "/v1/vehicles" {
		vehicles, err := a.provider.Vehicles(r.Context(), userID)
		if err != nil {
			a.providerError(w, err)
			return
		}
		a.json(w, http.StatusOK, map[string]any{"vehicles": vehicles})
		return
	}
	if strings.HasPrefix(r.URL.Path, "/v1/vehicles/") {
		a.vehicleResource(w, r, userID)
		return
	}
	a.compat(w, r, userID)
}

func (a *app) mockLogin(w http.ResponseWriter, r *http.Request) {
	if err := a.store.ensureUser(r.Context(), "mock-user"); err != nil {
		a.json(w, http.StatusInternalServerError, map[string]string{"error": "store_unavailable"})
		return
	}
	s, err := a.store.createSession(r.Context(), "mock-user")
	if err != nil {
		a.json(w, http.StatusInternalServerError, map[string]string{"error": "session_create_failed"})
		return
	}
	vehicles, _ := a.mock.Vehicles(r.Context(), s.UserID)
	a.json(w, http.StatusOK, map[string]any{
		"access_token": s.AccessToken, "refresh_token": s.RefreshToken,
		"expires_in": s.ExpiresIn, "user": map[string]string{"id": s.UserID}, "vehicles": vehicles,
	})
}

func (a *app) refresh(w http.ResponseWriter, r *http.Request) {
	token := bearerToken(r)
	if token == "" {
		var body struct {
			RefreshToken string `json:"refresh_token"`
		}
		_ = json.NewDecoder(r.Body).Decode(&body)
		token = body.RefreshToken
	}
	s, err := a.store.rotateSession(r.Context(), token)
	if err != nil {
		a.json(w, http.StatusUnauthorized, map[string]string{"error": err.Error()})
		return
	}
	a.json(w, http.StatusOK, map[string]any{"access_token": s.AccessToken, "refresh_token": s.RefreshToken, "expires_in": s.ExpiresIn})
}

func (a *app) logout(w http.ResponseWriter, r *http.Request) {
	token := bearerToken(r)
	if token == "" {
		a.json(w, http.StatusUnauthorized, map[string]string{"error": "session_required"})
		return
	}
	if err := a.store.revokeSession(r.Context(), token); err != nil {
		a.json(w, http.StatusInternalServerError, map[string]string{"error": "logout_failed"})
		return
	}
	a.json(w, http.StatusOK, map[string]string{"status": "logged_out"})
}

func (a *app) deleteAccount(w http.ResponseWriter, r *http.Request) {
	userID, ok := a.auth(w, r)
	if !ok {
		return
	}
	if err := a.store.deleteUser(r.Context(), userID); err != nil {
		a.json(w, http.StatusInternalServerError, map[string]string{"error": "account_delete_failed"})
		return
	}
	response := map[string]string{"status": "deleted"}
	if a.oauth != nil {
		if revokeURL := a.oauth.consentRevokeURL(); revokeURL != "" {
			response["tesla_consent_revoke_url"] = revokeURL
		}
	}
	a.json(w, http.StatusOK, response)
}

func (a *app) auth(w http.ResponseWriter, r *http.Request) (string, bool) {
	token := bearerToken(r)
	if token == "" {
		a.json(w, http.StatusUnauthorized, map[string]string{"error": "session_required"})
		return "", false
	}
	userID, err := a.store.userForAccess(r.Context(), token)
	if err != nil {
		a.json(w, http.StatusUnauthorized, map[string]string{"error": err.Error()})
		return "", false
	}
	return userID, true
}

func (a *app) compat(w http.ResponseWriter, r *http.Request, userID string) {
	path := strings.TrimSuffix(r.URL.Path, "/")
	switch {
	case path == "/api/ping" || path == "/api/readyz":
		a.json(w, http.StatusOK, map[string]string{"ping": "pong"})
	case path == "/api/matelink/v1/capabilities":
		features := []string{"live_status"}
		if a.hasMockHistory(userID) {
			features = append(features, "history_fixture")
		}
		a.json(w, http.StatusOK, map[string]any{"data": map[string]any{"adapter_version": "jourvolt-dev-api", "features": features}})
	case strings.HasPrefix(path, "/api/matelink/v1/cars/"):
		a.adapterResource(w, r, userID, path)
	case path == "/api/v1/globalsettings":
		a.json(w, http.StatusOK, map[string]any{"data": map[string]any{"settings": map[string]any{"teslamate_units": map[string]string{"unit_of_length": "km", "unit_of_temperature": "C"}}}})
	case path == "/api/v1/cars":
		a.cars(w, r, userID)
	case strings.HasPrefix(path, "/api/v1/cars/"):
		a.carResource(w, r, userID, path)
	default:
		a.json(w, http.StatusNotFound, map[string]string{"error": "not_found"})
	}
}

func (a *app) adapterResource(w http.ResponseWriter, r *http.Request, userID, path string) {
	parts := strings.Split(strings.TrimPrefix(path, "/api/matelink/v1/cars/"), "/")
	if len(parts) < 2 {
		a.json(w, http.StatusNotFound, map[string]string{"error": "vehicle_not_found"})
		return
	}
	carID, err := strconv.Atoi(parts[0])
	if err != nil {
		a.json(w, http.StatusNotFound, map[string]string{"error": "vehicle_not_found"})
		return
	}
	if !a.requireVehicle(w, r, userID, carID) {
		return
	}
	switch parts[1] {
	case "snapshot":
		a.status(w, r, userID, carID, true)
	case "parked":
		a.json(w, http.StatusOK, map[string]any{"data": nil, "error": "history_not_collected"})
	default:
		a.json(w, http.StatusNotFound, map[string]string{"error": "not_found"})
	}
}

func (a *app) cars(w http.ResponseWriter, r *http.Request, userID string) {
	vehicles, err := a.provider.Vehicles(r.Context(), userID)
	if err != nil {
		a.providerError(w, err)
		return
	}
	items := make([]map[string]any, 0, len(vehicles))
	driveCount, chargeCount := 0, 0
	if a.hasMockHistory(userID) {
		driveCount, chargeCount = len(mockDriveFixtures()), len(mockChargeFixtures())
	}
	for _, v := range vehicles {
		items = append(items, map[string]any{
			"car_id": v.ID, "name": v.DisplayName,
			"car_details":     map[string]any{"model": emptyAsNil(v.Model), "trim_badging": emptyAsNil(v.TrimBadging), "efficiency": nil},
			"car_exterior":    map[string]any{"exterior_color": emptyAsNil(v.ExteriorColor), "wheel_type": emptyAsNil(v.WheelType)},
			"teslamate_stats": map[string]any{"total_charges": chargeCount, "total_drives": driveCount},
		})
	}
	a.json(w, http.StatusOK, map[string]any{"data": map[string]any{"cars": items}})
}

func (a *app) carResource(w http.ResponseWriter, r *http.Request, userID, path string) {
	parts := strings.Split(strings.TrimPrefix(path, "/api/v1/cars/"), "/")
	if len(parts) == 0 || parts[0] == "" {
		a.json(w, http.StatusNotFound, map[string]string{"error": "not_found"})
		return
	}
	carID, err := strconv.Atoi(parts[0])
	if err != nil {
		a.json(w, http.StatusNotFound, map[string]string{"error": "vehicle_not_found"})
		return
	}
	if !a.requireVehicle(w, r, userID, carID) {
		return
	}
	if len(parts) == 1 {
		a.cars(w, r, userID)
		return
	}
	switch parts[1] {
	case "status":
		a.status(w, r, userID, carID, false)
	case "charges":
		if len(parts) > 2 && parts[2] == "current" {
			a.json(w, http.StatusOK, map[string]any{"data": nil, "error": "No active charging in progress."})
		} else if len(parts) > 2 && a.hasMockHistory(userID) {
			a.mockChargeDetail(w, parts[2])
		} else if a.hasMockHistory(userID) {
			a.json(w, http.StatusOK, map[string]any{"data": map[string]any{
				"charges": paginateFixture(mockChargeFixtures(), r), "meta": a.historyMeta(userID),
			}})
		} else {
			a.json(w, http.StatusOK, map[string]any{"data": map[string]any{
				"charges": []any{}, "meta": a.historyMeta(userID),
			}})
		}
	case "drives":
		if len(parts) > 2 && a.hasMockHistory(userID) {
			a.mockDriveDetail(w, parts[2])
		} else if a.hasMockHistory(userID) {
			a.json(w, http.StatusOK, map[string]any{"data": map[string]any{
				"drives": paginateFixture(mockDriveFixtures(), r), "meta": a.historyMeta(userID),
			}})
		} else {
			a.json(w, http.StatusOK, map[string]any{"data": map[string]any{
				"drives": []any{}, "meta": a.historyMeta(userID),
			}})
		}
	case "battery-health":
		a.json(w, http.StatusOK, map[string]any{"data": map[string]any{
			"battery_health": nil, "meta": a.unsupportedMeta(userID),
		}})
	case "updates":
		a.json(w, http.StatusOK, map[string]any{"data": map[string]any{"updates": []any{}}})
	default:
		a.json(w, http.StatusNotFound, map[string]string{"error": "not_found"})
	}
}

func (a *app) vehicleResource(w http.ResponseWriter, r *http.Request, userID string) {
	parts := strings.Split(strings.TrimPrefix(r.URL.Path, "/v1/vehicles/"), "/")
	if len(parts) < 1 {
		a.json(w, http.StatusNotFound, map[string]string{"error": "vehicle_not_found"})
		return
	}
	vehicleID, err := strconv.Atoi(parts[0])
	if err != nil || !a.requireVehicle(w, r, userID, vehicleID) {
		return
	}
	if len(parts) == 2 && parts[1] == "status" {
		a.status(w, r, userID, vehicleID, false)
		return
	}
	a.json(w, http.StatusNotFound, map[string]string{"error": "not_found"})
}

func (a *app) requireVehicle(w http.ResponseWriter, r *http.Request, userID string, vehicleID int) bool {
	owned, err := a.vehicleOwned(r.Context(), userID, vehicleID)
	if err != nil {
		a.providerError(w, err)
		return false
	}
	if owned {
		return true
	}
	a.json(w, http.StatusNotFound, map[string]string{"error": "vehicle_not_found"})
	return false
}

func (a *app) vehicleOwned(ctx context.Context, userID string, vehicleID int) (bool, error) {
	vehicles, err := a.provider.Vehicles(ctx, userID)
	if err != nil {
		return false, err
	}
	for _, vehicle := range vehicles {
		if vehicle.ID == vehicleID {
			return true, nil
		}
	}
	return false, nil
}

