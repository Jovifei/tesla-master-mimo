func (a *app) providerError(w http.ResponseWriter, err error) {
	switch {
	case errors.Is(err, errNotConfigured):
		a.json(w, http.StatusServiceUnavailable, map[string]string{"error": "provider_not_configured"})
	case errors.Is(err, errTeslaReauthorization):
		a.json(w, http.StatusUnauthorized, map[string]string{"error": "tesla_reauthorization_required"})
	case errors.Is(err, errTeslaRateLimited):
		w.Header().Set("Retry-After", "60")
		a.json(w, http.StatusTooManyRequests, map[string]string{"error": "tesla_rate_limited"})
	case errors.Is(err, errVehicleNotFound):
		a.json(w, http.StatusNotFound, map[string]string{"error": "vehicle_not_found"})
	case errors.Is(err, errTeslaUnavailable):
		a.json(w, http.StatusServiceUnavailable, map[string]string{"error": "tesla_temporarily_unavailable"})
	default:
		a.json(w, http.StatusBadGateway, map[string]string{"error": "upstream_unavailable"})
	}
}

func emptyAsNil(value string) any {
	if value == "" {
		return nil
	}
	return value
}

func bearerToken(r *http.Request) string {
	value := r.Header.Get("Authorization")
	if len(value) > len("Bearer ") && strings.EqualFold(value[:len("Bearer ")], "Bearer ") {
		return strings.TrimSpace(value[len("Bearer "):])
	}
	return ""
}

func (a *app) json(w http.ResponseWriter, status int, payload any) {
	data, err := json.Marshal(payload)
	if err != nil {
		http.Error(w, `{"error":"serialization_failed"}`, http.StatusInternalServerError)
		return
	}
	w.Header().Set("Content-Type", "application/json")
	w.Header().Set("Cache-Control", "no-store")
	w.WriteHeader(status)
	_, _ = w.Write(data)
}

func (a *app) readyz(w http.ResponseWriter, r *http.Request) {
	if a.store == nil || a.store.pool == nil {
		a.json(w, http.StatusServiceUnavailable, map[string]string{"status": "not_ready"})
		return
	}
	ctx, cancel := context.WithTimeout(r.Context(), 2*time.Second)
	defer cancel()
	if err := a.store.pool.Ping(ctx); err != nil {
		a.json(w, http.StatusServiceUnavailable, map[string]string{"status": "not_ready"})
		return
	}
	a.json(w, http.StatusOK, map[string]any{
		"status": "ok", "mode": a.mode, "persistence": "postgres",
	})
}

func main() {
	ctx := context.Background()
	dsn := os.Getenv("DATABASE_URL")
	if dsn == "" {
		dsn = "postgres://jourvolt:jourvolt@127.0.0.1:5432/jourvolt?sslmode=disable"
	}
	store, err := openStore(ctx, dsn)
	if err != nil {
		log.Fatalf("jourvolt store: %v", err)
	}
	defer store.close()
	enableMock, err := loadBool(os.Getenv, "JOURVOLT_ENABLE_MOCK", false)
	if err != nil {
		log.Fatal(err)
	}
	enableMockHistory, err := loadBool(os.Getenv, "JOURVOLT_ENABLE_MOCK_HISTORY", false)
	if err != nil {
		log.Fatal(err)
	}
	if enableMockHistory && !enableMock {
		log.Fatal("JOURVOLT_ENABLE_MOCK_HISTORY requires JOURVOLT_ENABLE_MOCK=true")
	}
	teslaSettings, err := loadTeslaConfig(os.Getenv)
	if err != nil {
		log.Fatal(err)
	}
	httpClient := &http.Client{Timeout: 20 * time.Second}
	mock := mockProvider{}
	dataProvider := provider(unconfiguredProvider{})
	mode := "unconfigured"
	var oauth *teslaOAuth
	if teslaSettings != nil {
		cipher, err := newTokenCipher(teslaSettings.TokenKey)
		if err != nil {
			log.Fatal(err)
		}
		tokenManager := &teslaTokenManager{store: store, cipher: cipher, config: teslaSettings, client: httpClient}
		fleet := &fleetProvider{
			store: store, tokens: tokenManager, cipher: cipher,
			client: httpClient, baseURL: teslaSettings.FleetAPIBase,
		}
		oauth = newTeslaOAuth(teslaSettings, store, cipher, httpClient)
		dataProvider = fleet
		mode = "fleet"
		if enableMock {
			dataProvider = routingProvider{mock: mock, fleet: fleet}
			mode = "fleet_with_debug_mock"
		}
	} else if enableMock {
		dataProvider = mock
		mode = "mock_only"
	}
	a := &app{
		store: store, mock: mock, provider: dataProvider, oauth: oauth,
		mockEnabled: enableMock, mockHistoryEnabled: enableMockHistory, mode: mode,
	}
	addr := os.Getenv("LISTEN_ADDR")
	if addr == "" {
		addr = ":8080"
	}
	log.Printf("jourvolt api listening on %s mode=%s", addr, mode)
	if err := http.ListenAndServe(addr, a); err != nil {
		log.Fatal(fmt.Errorf("listen: %w", err))
	}
}
