var errNotConfigured = errors.New("provider_not_configured")

type store struct{ pool *pgxpool.Pool }

type session struct {
	AccessToken  string
	RefreshToken string
	ExpiresIn    int64
	UserID       string
}

func openStore(ctx context.Context, dsn string) (*store, error) {
	pool, err := pgxpool.New(ctx, dsn)
	if err != nil {
		return nil, err
	}
	if err = pool.Ping(ctx); err != nil {
		pool.Close()
		return nil, err
	}
	_, err = pool.Exec(ctx, `
CREATE TABLE IF NOT EXISTS jourvolt_users (
    id TEXT PRIMARY KEY,
    provider_sub TEXT UNIQUE NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS jourvolt_sessions (
    id BIGSERIAL PRIMARY KEY,
    user_id TEXT NOT NULL REFERENCES jourvolt_users(id) ON DELETE CASCADE,
    access_hash TEXT UNIQUE NOT NULL,
    refresh_hash TEXT UNIQUE NOT NULL,
    access_expires_at TIMESTAMPTZ NOT NULL,
    refresh_expires_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ
);
CREATE TABLE IF NOT EXISTS jourvolt_auth_transactions (
    state_hash TEXT PRIMARY KEY,
    transaction_hash TEXT UNIQUE NOT NULL,
    nonce TEXT NOT NULL,
    terms_version TEXT,
    privacy_version TEXT,
    expires_at TIMESTAMPTZ NOT NULL,
    consumed_at TIMESTAMPTZ
);
CREATE TABLE IF NOT EXISTS jourvolt_login_tickets (
    ticket_hash TEXT PRIMARY KEY,
    user_id TEXT NOT NULL REFERENCES jourvolt_users(id) ON DELETE CASCADE,
    expires_at TIMESTAMPTZ NOT NULL,
    consumed_at TIMESTAMPTZ
);
CREATE TABLE IF NOT EXISTS jourvolt_tesla_tokens (
    user_id TEXT PRIMARY KEY REFERENCES jourvolt_users(id) ON DELETE CASCADE,
    access_ciphertext TEXT NOT NULL,
    refresh_ciphertext TEXT NOT NULL,
    access_expires_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS jourvolt_user_consents (
    user_id TEXT PRIMARY KEY REFERENCES jourvolt_users(id) ON DELETE CASCADE,
    terms_version TEXT NOT NULL,
    privacy_version TEXT NOT NULL,
    accepted_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE IF NOT EXISTS jourvolt_vehicles (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id TEXT NOT NULL REFERENCES jourvolt_users(id) ON DELETE CASCADE,
    provider_vehicle_id TEXT NOT NULL,
    vin_ciphertext TEXT NOT NULL,
    display_name TEXT NOT NULL,
    state TEXT NOT NULL,
    model TEXT,
    trim_badging TEXT,
    exterior_color TEXT,
    wheel_type TEXT,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (user_id, provider_vehicle_id)
);
ALTER TABLE jourvolt_auth_transactions ADD COLUMN IF NOT EXISTS terms_version TEXT;
ALTER TABLE jourvolt_auth_transactions ADD COLUMN IF NOT EXISTS privacy_version TEXT;`)
	if err != nil {
		pool.Close()
		return nil, err
	}
	return &store{pool: pool}, nil
}

func (s *store) close() { s.pool.Close() }

func hashToken(value string) string {
	sum := sha256.Sum256([]byte(value))
	return hex.EncodeToString(sum[:])
}

func randomToken() (string, error) {
	buf := make([]byte, 32)
	if _, err := rand.Read(buf); err != nil {
		return "", err
	}
	return hex.EncodeToString(buf), nil
}

func (s *store) ensureUser(ctx context.Context, id string) error {
	_, err := s.pool.Exec(ctx, `
INSERT INTO jourvolt_users(id, provider_sub) VALUES ($1, $1)
ON CONFLICT (id) DO NOTHING`, id)
	return err
}

func (s *store) createSession(ctx context.Context, userID string) (session, error) {
	access, err := randomToken()
	if err != nil {
		return session{}, err
	}
	refresh, err := randomToken()
	if err != nil {
		return session{}, err
	}
	now := time.Now().UTC()
	_, err = s.pool.Exec(ctx, `
INSERT INTO jourvolt_sessions(user_id, access_hash, refresh_hash, access_expires_at, refresh_expires_at)
VALUES ($1, $2, $3, $4, $5)`, userID, hashToken(access), hashToken(refresh),
		now.Add(accessLifetime), now.Add(refreshLifetime))
	if err != nil {
		return session{}, err
	}
	return session{AccessToken: access, RefreshToken: refresh, ExpiresIn: int64(accessLifetime.Seconds()), UserID: userID}, nil
}

func (s *store) userForAccess(ctx context.Context, token string) (string, error) {
	var userID string
	err := s.pool.QueryRow(ctx, `
SELECT user_id FROM jourvolt_sessions
WHERE access_hash=$1 AND revoked_at IS NULL AND access_expires_at > now()`, hashToken(token)).Scan(&userID)
	if errors.Is(err, pgx.ErrNoRows) {
		return "", errors.New("session_required")
	}
	return userID, err
}

func (s *store) rotateSession(ctx context.Context, refreshToken string) (session, error) {
	access, err := randomToken()
	if err != nil {
		return session{}, err
	}
	newRefresh, err := randomToken()
	if err != nil {
		return session{}, err
	}
	tx, err := s.pool.Begin(ctx)
	if err != nil {
		return session{}, err
	}
	defer tx.Rollback(ctx)
	var userID string
	err = tx.QueryRow(ctx, `
SELECT user_id FROM jourvolt_sessions
WHERE refresh_hash=$1 AND revoked_at IS NULL AND refresh_expires_at > now()
FOR UPDATE`, hashToken(refreshToken)).Scan(&userID)
	if errors.Is(err, pgx.ErrNoRows) {
		return session{}, errors.New("refresh_required")
	}
	if err != nil {
		return session{}, err
	}
	now := time.Now().UTC()
	_, err = tx.Exec(ctx, `
UPDATE jourvolt_sessions SET access_hash=$1, refresh_hash=$2,
access_expires_at=$3, refresh_expires_at=$4
WHERE refresh_hash=$5`, hashToken(access), hashToken(newRefresh), now.Add(accessLifetime), now.Add(refreshLifetime), hashToken(refreshToken))
	if err != nil {
		return session{}, err
	}
	if err = tx.Commit(ctx); err != nil {
		return session{}, err
	}
	return session{AccessToken: access, RefreshToken: newRefresh, ExpiresIn: int64(accessLifetime.Seconds()), UserID: userID}, nil
}

func (s *store) revokeSession(ctx context.Context, accessToken string) error {
	_, err := s.pool.Exec(ctx, `
UPDATE jourvolt_sessions
SET revoked_at=COALESCE(revoked_at, now())
WHERE access_hash=$1`, hashToken(accessToken))
	return err
}

func (s *store) deleteUser(ctx context.Context, userID string) error {
	_, err := s.pool.Exec(ctx, `DELETE FROM jourvolt_users WHERE id=$1`, userID)
	return err
}

